"""
Prepare Seti, Setra's mascot, for the web app.

Source renders (transparent, 1254px): docs/brand/seti/<mood>.webp
Output: apps/web/public/seti/<mood>.webp (trimmed, 560px tall) and
        apps/web/src/components/seti-eyes.ts (eye positions and eyelid colours, used for blinking).

Cleans the renders for any background: makes the body fully opaque, removes faint stray pixels
around the figure, trims to the figure and resizes.

Run: python3 -m venv /tmp/seti && /tmp/seti/bin/pip install numpy pillow && /tmp/seti/bin/python scripts/prepare-seti.py
"""
import json
import os
from collections import deque

import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs/brand/seti")
OUT = os.path.join(ROOT, "apps/web/public/seti")
EYES_TS = os.path.join(ROOT, "apps/web/src/components/seti-eyes.ts")
MOODS = ["welcome", "focused", "success", "curious", "attention", "resting"]
OPEN_EYES = {"welcome", "focused", "curious", "attention"}
HEIGHT = 560


def components(mask):
    h, w = mask.shape
    lab = np.zeros((h, w), np.int32)
    comps = []
    cur = 0
    for sy, sx in zip(*np.nonzero(mask)):
        if lab[sy, sx]:
            continue
        cur += 1
        lab[sy, sx] = cur
        pts = []
        dq = deque([(sy, sx)])
        while dq:
            y, x = dq.popleft()
            pts.append((y, x))
            for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                ny, nx = y + dy, x + dx
                if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not lab[ny, nx]:
                    lab[ny, nx] = cur
                    dq.append((ny, nx))
        ys = [p[0] for p in pts]
        xs = [p[1] for p in pts]
        comps.append({"id": cur, "area": len(pts), "x0": min(xs), "x1": max(xs), "y0": min(ys), "y1": max(ys)})
    return lab, comps


eyes_out = {}
for mood in MOODS:
    im = np.asarray(Image.open(os.path.join(SRC, f"{mood}.webp")).convert("RGBA")).astype(np.float32)
    a = im[..., 3]
    # Keep only the figure: the largest solid region, grown a little to keep soft edges.
    lab, comps = components(a > 200)
    main = max(comps, key=lambda c: c["area"])["id"]
    keep = np.asarray(Image.fromarray(((lab == main) * 255).astype(np.uint8)).filter(ImageFilter.MaxFilter(9))) > 0
    a[~keep] = 0
    a[a < 12] = 0
    a[a > 235] = 255  # body fully opaque
    im[..., 3] = a
    img = Image.fromarray(im.astype(np.uint8), "RGBA")
    x0, y0, x1, y1 = img.getbbox()
    pad = 8
    img = img.crop((max(0, x0 - pad), max(0, y0 - pad), min(img.width, x1 + pad), min(img.height, y1 + pad)))
    scale = HEIGHT / img.height
    img = img.resize((round(img.width * scale), HEIGHT), Image.LANCZOS)
    img.save(os.path.join(OUT, f"{mood}.webp"), quality=90, method=6)

    info = {"w": img.width, "h": img.height, "eyes": []}
    if mood in OPEN_EYES:
        arr = np.asarray(img).astype(np.float32)
        rgb, al = arr[..., :3], arr[..., 3]
        dark = (rgb.max(2) < 70) & (al > 200)
        _, dcomps = components(dark)
        cands = []
        for c in dcomps:
            bw, bh = c["x1"] - c["x0"] + 1, c["y1"] - c["y0"] + 1
            fill = c["area"] / (bw * bh)
            if c["area"] > 150 and 0.9 <= bh / bw <= 2.2 and fill > 0.55:
                cands.append(c)
        cands = sorted(cands, key=lambda c: c["area"], reverse=True)[:2]
        for c in sorted(cands, key=lambda c: c["x0"]):
            bw, bh = c["x1"] - c["x0"] + 1, c["y1"] - c["y0"] + 1
            # Eyelid colour: the median of the body in a ring around the eye (skipping dark marks).
            cy, cx = (c["y0"] + c["y1"]) / 2, (c["x0"] + c["x1"]) / 2
            ry, rx = bh / 2, bw / 2
            yy, xx = np.mgrid[0 : img.height, 0 : img.width]
            d = np.sqrt(((yy - cy) / ry) ** 2 + ((xx - cx) / rx) ** 2)
            ring = (d > 1.25) & (d < 1.7) & (al > 250) & (rgb.max(2) > 120)
            col = np.median(rgb[ring], axis=0) if ring.any() else np.array([40, 130, 230])
            info["eyes"].append({
                "x": round(c["x0"] / img.width, 4), "y": round(c["y0"] / img.height, 4),
                "w": round(bw / img.width, 4), "h": round(bh / img.height, 4),
                "lid": "#%02x%02x%02x" % tuple(int(v) for v in col),
            })
    eyes_out[mood] = info
    print(mood, img.size, len(info["eyes"]), "eyes")

with open(EYES_TS, "w") as f:
    f.write("// Generated by scripts/prepare-seti.py. Do not edit by hand.\n")
    f.write("// Image size of each pose, and eye boxes (fractions of the image) with the eyelid colour, for blinking.\n\n")
    f.write("export const SETI_ART = " + json.dumps(eyes_out, indent=2) + " as const;\n")
